interface Props {
  /** 인물의 이름표 (사건 자료의 id) */
  id: string;
  /** 화면에서의 한 변(px). 점 하나가 2px 이 되도록 32 를 기본으로 한다 */
  size?: number;
  className?: string;
}

export function Silhouette({ id, size = 32, className }: Props) {
  const rows = BUSTS[id];
  const runs: { x: number; y: number; w: number }[] = [];
  rows?.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      if (row[x] !== "#") continue;
      let w = 1;
      while (row[x + w] === "#") w++;
      runs.push({ x, y, w });
      x += w - 1;
    }
  });
  return (
    <svg className={["bust", className].filter(Boolean).join(" ")} width={size} height={size} viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden="true" data-bust={rows ? id : "none"}>
      {rows ? (
        runs.map((r) => <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} fill="currentColor" />)
      ) : (
        // 아무도 아니다: 빈 자리
        <>
          {[2, 5, 8, 11].flatMap((n) => [
            <rect key={`t${n}`} x={n} y={2} width={2} height={1} fill="currentColor" />,
            <rect key={`b${n}`} x={n + 1} y={13} width={2} height={1} fill="currentColor" />,
            <rect key={`l${n}`} x={2} y={n + 1} width={1} height={2} fill="currentColor" />,
            <rect key={`r${n}`} x={13} y={n} width={1} height={2} fill="currentColor" />,
          ])}
        </>
      )}
    </svg>
  );
}
